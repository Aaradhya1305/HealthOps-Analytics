#TOTAL ORDERS, DELIVERED ORDERS, REVENUE AND AVERAGE ORDER VALUE(AOV) FOR OCT'26

SELECT COUNT(ORDER_ID) TOTAL_ORDERS FROM ORDERS
WHERE YEAR (ORDER_DATETIME) = 2026 AND MONTH(ORDER_DATETIME) = 10;

SELECT COUNT(ORDER_ID) DELIVERED_ORDERS FROM ORDERS WHERE ORDER_STATUS = "Delivered"
AND YEAR (ORDER_DATETIME) = 2026 AND MONTH(ORDER_DATETIME) = 10;

SELECT SUM(ORDER_VALUE) REVENUE FROM ORDERS WHERE ORDER_STATUS = "DELIVERED"
AND YEAR (ORDER_DATETIME) = 2026 AND MONTH(ORDER_DATETIME) = 10;

SELECT ROUND(SUM(ORDER_VALUE)/COUNT(ORDER_ID),2) AOV FROM ORDERS
WHERE YEAR (ORDER_DATETIME) = 2026 AND MONTH(ORDER_DATETIME) = 10;


#TOP 10 CITIES BY TOTAL ORDERS AND THERE % SHARE IN ORDERS

SELECT * FROM CUSTOMERS;
SELECT * FROM CITIES;
SELECT * FROM ORDERS;

SELECT CITIES.CITY_NAME,
COUNT(ORDERS.ORDER_ID) TOTAL_ORDERS,
CONCAT(ROUND((COUNT(ORDERS.ORDER_ID)/(SELECT COUNT(ORDER_ID) FROM ORDERS))*100, 2), "%") PERCENT_OF_TOTAL_ORDERS
FROM CITIES JOIN CUSTOMERS
ON CITIES.CITY_ID = CUSTOMERS.CITY_ID
JOIN ORDERS
ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID
GROUP BY CITIES.CITY_NAME 
ORDER BY TOTAL_ORDERS DESC LIMIT 10;


#FOR EACH EXPRESS CITY FIND % OF EXPRESS ORDERS DELIVERED AFTER 60 MINS

WITH CTE1 AS (SELECT CITIES. CITY_NAME, timestampdiff(MINUTE, ORDERS.ORDER_DATETIME, ORDERS.DELIVERED_DATETIME) MINUTES_TAKEN
FROM CITIES JOIN CUSTOMERS
USING (CITY_ID)
JOIN ORDERS
USING(CUSTOMER_ID)
WHERE ORDERS.DELIVERY_TYPE = "EXPRESS")

SELECT CITY_NAME,
COUNT(MINUTES_TAKEN)EXPRESS_ORDERS, 
ROUND((SUM(MINUTES_TAKEN >60)/COUNT(MINUTES_TAKEN))*100, 2) PERCENT_OF_LATE_EXPRESS_ORDERS
FROM CTE1
GROUP BY CITY_NAME 
ORDER BY PERCENT_OF_LATE_EXPRESS_ORDERS DESC;


#COMPARE FEVER AND COLD SALES IN SEPT-OCT'26 
#WITH SEPT-OCT'25, YOY GROWTH
SELECT * FROM PRODUCTS;
SELECT * FROM ORDERS;
SELECT * FROM ORDER_ITEMS;

WITH CTE1 AS (SELECT CITIES.REGION,
ORDERS.ORDER_DATETIME,
ORDER_ITEMS.QUANTITY*ORDER_ITEMS.UNIT_PRICE AS SALES
FROM CITIES JOIN CUSTOMERS
USING(CITY_ID)
JOIN ORDERS
USING(CUSTOMER_ID)
JOIN ORDER_ITEMS
USING(ORDER_ID)
JOIN PRODUCTS 
USING(PRODUCT_ID)
WHERE PRODUCTS.CATEGORY = "FEVER & COLD"
AND ORDER_ITEMS.ITEM_STATUS = "FULFILLED"
AND ORDERS.ORDER_STATUS = "DELIVERED") ,

CTE2025 AS (SELECT REGION, SUM(SALES) SALES_25
FROM CTE1 
WHERE ORDER_DATETIME >= "2025-09-01" AND ORDER_DATETIME <= "2025-10-31"
GROUP BY REGION),

CTE2026 AS (SELECT REGION, SUM(SALES) SALES_26
FROM CTE1 
WHERE ORDER_DATETIME >= "2026-09-01" AND ORDER_DATETIME <= "2026-10-31"
GROUP BY REGION)

SELECT CTE2025.REGION, CTE2025.SALES_25, CTE2026.SALES_26,
ROUND(((CTE2026.SALES_26-CTE2025.SALES_25)/CTE2025.SALES_25)*100,2) YOY_GROWTH
FROM CTE2025 JOIN CTE2026
USING(REGION) 
ORDER BY YOY_GROWTH DESC; 


# ANALYSING WoW GROWTH OF FEVER PANEL TESTING SINCE AUG'26 AND FLAGGING TOP 5
WITH WEEKLY AS (
    SELECT
        C.CITY_NAME,
        YEARWEEK(B.BOOKING_DATETIME, 3) AS YR_WK,
        COUNT(*) AS BOOKINGS
    FROM LAB_BOOKINGS B
    JOIN LAB_TESTS T
        ON T.TEST_ID = B.TEST_ID
    JOIN PHLEBOTOMISTS PH
        ON PH.PHLEBOTOMIST_ID = B.PHLEBOTOMIST_ID
    JOIN CITIES C
        ON C.CITY_ID = PH.CITY_ID
    WHERE T.TEST_CATEGORY = 'Fever PaneL'
      AND B.BOOKING_DATETIME >= '2026-08-01'
    GROUP BY C.CITY_NAME, YR_WK
),
WOW AS (
    SELECT
        CITY_NAME,
        YR_WK,
        BOOKINGS,
        LAG(BOOKINGS) OVER (
            PARTITION BY CITY_NAME
            ORDER BY YR_WK
        ) AS PREV_WEEK
    FROM WEEKLY
)
SELECT
    CITY_NAME,
    YR_WK,
    PREV_WEEK,
    BOOKINGS,
    ROUND(100 * (BOOKINGS - PREV_WEEK) / PREV_WEEK, 1) AS WOW_GROWTH_PCT
FROM WOW
WHERE BOOKINGS >= 15
  AND PREV_WEEK > 0
  AND (BOOKINGS - PREV_WEEK) / PREV_WEEK > 0.5
ORDER BY YR_WK, CITY_NAME DESC;

# FINDING FEVER MEDICINES THAT WENT OUT OF STOCK IN SEPT-OCT'26
# WITH TOTAL UNIT LOST AND AFFECTED ORDERS
SELECT
    C.CITY_NAME,
    P.PRODUCT_NAME,
    COUNT(DISTINCT OI.ORDER_ID) AS ORDERS_AFFECTED,
    SUM(OI.QUANTITY)         AS UNITS_LOST
FROM ORDER_ITEMS OI
JOIN ORDERS O     ON O.ORDER_ID = OI.ORDER_ID
JOIN PRODUCTS P   ON P.PRODUCT_ID = OI.PRODUCT_ID
JOIN CUSTOMERS CU ON CU.CUSTOMER_ID = O.CUSTOMER_ID
JOIN CITIES C     ON C.CITY_ID = CU.CITY_ID
WHERE OI.ITEM_STATUS = 'OUT OF STOCK'
  AND P.CATEGORY = 'Fever & Cold '
  AND O.ORDER_DATETIME >= '2026-09-01'
  AND O.ORDER_DATETIME <  '2026-11-01'
GROUP BY C.CITY_NAME, P.PRODUCT_NAME
HAVING ORDERS_AFFECTED >= 5
ORDER BY ORDERS_AFFECTED DESC;

#RANKING PHEBOTOMISTS WITHIN EACH CITY BY SAMPLE COLLECTION COMPLETITION
WITH PERF AS (
    SELECT C.CITY_NAME, PH.PHLEBOTOMIST_NAME,
        SUM(B.COLLECTION_STATUS = 'COLLECTED') AS COLLECTED,
        SUM(B.COLLECTION_STATUS = 'MISSED')    AS MISSED
    FROM LAB_BOOKINGS B
    JOIN PHLEBOTOMISTS PH
        ON PH.PHLEBOTOMIST_ID = B.PHLEBOTOMIST_ID
    JOIN CITIES C ON C.CITY_ID = PH.CITY_ID
    GROUP BY C.CITY_NAME, PH.PHLEBOTOMIST_ID,
        PH.PHLEBOTOMIST_NAME
),
RANKED AS (
    SELECT *, DENSE_RANK() OVER (
        PARTITION BY CITY_NAME
        ORDER BY COLLECTED DESC) AS RNK
    FROM PERF
)
SELECT CITY_NAME, RNK, PHLEBOTOMIST_NAME, COLLECTED, MISSED
FROM RANKED
WHERE RNK <= 3
ORDER BY CITY_NAME, RNK;

#FINDING THE % OF SWITCH OF ITEMS TO GENERIC ITEMS
# AND ALSO THE SAVINGS OF CUSTOMERS FROM IT
SELECT
    BOUGHT.CATEGORY,
    COUNT(*) AS TOTAL_ITEMS,
    SUM(OI.SUBSTITUTED_FROM_PRODUCT_ID IS NOT NULL)
        AS SWITCHED_ITEMS,
    ROUND(100 * SUM(OI.SUBSTITUTED_FROM_PRODUCT_ID
        IS NOT NULL) / COUNT(*), 2) AS SWITCHED_PCT,
    ROUND(SUM((ORIGINAL.SELLING_PRICE - OI.UNIT_PRICE)
        * OI.QUANTITY), 2) AS CUSTOMER_SAVINGS
FROM ORDER_ITEMS OI
JOIN PRODUCTS BOUGHT
    ON BOUGHT.PRODUCT_ID = OI.PRODUCT_ID
LEFT JOIN PRODUCTS ORIGINAL
    ON ORIGINAL.PRODUCT_ID = OI.SUBSTITUTED_FROM_PRODUCT_ID
WHERE OI.ITEM_STATUS = 'FULFILLED'
GROUP BY BOUGHT.CATEGORY
ORDER BY CUSTOMER_SAVINGS DESC;


